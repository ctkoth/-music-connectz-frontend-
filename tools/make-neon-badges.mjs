// Generates the neon BADGE medals — one chassis, Corey's emoji in the middle.
//
// Same idea as make-neon-icons.mjs: the frame, glow and wordmark live here ONCE
// and each badge brings only its emoji, name and colour, so twenty medals can't
// drift into twenty styles. The emoji is Corey's placeholder ("add my emoji for
// placeholders") and the medal is the neon dress it wears until his art lands.
//
//   node tools/make-neon-badges.mjs
//
// Writes public/icons/badge_<key>-neon.svg. HIS ART WINS: a committed
// `badgez.<name>.jpg` is mapped to the same registry key in
// tools/build-icon-manifest.mjs, and IconImg tries his file before this one —
// so dropping the jpg in and rebuilding the manifest is the whole job.
import { writeFileSync, mkdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const OUT = join(dirname(fileURLToPath(import.meta.url)), "..", "public", "icons");
const C = { cyan: "#22e6ff", pink: "#ff2bd1", purple: "#a855f7", gold: "#ffcf3f",
  ember: "#ff5500", emerald: "#34d399", ink: "#f4f2ff", silver: "#cbd5e1" };

// [badge key, name as the medal says it, emoji, accent]. The keys are the
// server's (apps/economy/badgez_wave.py, thoroughz.py); badgeArt.test.mjs holds
// this list and the registry in App.jsx to each other.
export const MEDALS = [
  ["high_notez", "High NoteZ", "🎤", C.pink],
  ["hot_barz", "Hot BarZ", "🎙️", C.ember],
  ["six_stringz", "Six StringZ", "🎸", C.cyan],
  ["low_endz", "Low EndZ", "🔊", C.purple],
  ["ivory_keyz", "Ivory KeyZ", "🎹", C.ink],
  ["deep_pocketz", "Deep PocketZ", "🥁", C.ember],
  ["golden_bowz", "Golden BowZ", "🎻", C.gold],
  ["silver_flutez", "Silver FluteZ", "🪈", C.silver],
  ["smooth_saxz", "Smooth SaxZ", "🎷", C.gold],
  ["reed_tonez", "Reed ToneZ", "🎼", C.purple],
  ["brass_blastz", "Brass BlastZ", "🎺", C.gold],
  ["royal_ratingz", "Royal RatingZ", "💰", C.emerald],
  ["cut_royaltiez", "Cut RoyaltieZ", "✂️", C.ember],
  ["thorough", "Thorough", "💯", C.pink],
  ["decent", "Decent", "🥈", C.silver],
  ["legendary", "Legendary", "🥇", C.gold],
  ["supreme", "Supreme", "🌟", C.cyan],
  ["perfect", "Perfect", "💎", C.cyan],
];

function wordmark(name, accent) {
  const lit = name.endsWith("Z");
  const head = lit ? name.slice(0, -1) : name;
  const size = name.length >= 13 ? 50 : name.length >= 10 ? 58 : 68;
  return `<text x="256" y="452" text-anchor="middle" font-size="${size}" fill="${C.ink}" filter="url(#soft)">${head}${lit ? `<tspan fill="${accent}">Z</tspan>` : ""}</text>`;
}

function medal(name, emoji, accent) {
  // A hexagon: a medal, not a tab tile, so a badge never reads as an app.
  const hex = "M256 40 L420 135 L420 325 L256 420 L92 325 L92 135 Z";
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 512 512" width="512" height="512" role="img" aria-label="${name}">
  <title>${name}</title>
  <!-- Generated by tools/make-neon-badges.mjs — edit it there, not here. -->
  <defs>
    <radialGradient id="bg" cx="50%" cy="20%" r="90%">
      <stop offset="0%" stop-color="#1b1136"/><stop offset="100%" stop-color="#07060d"/>
    </radialGradient>
    <filter id="glow" x="-40%" y="-40%" width="180%" height="180%">
      <feGaussianBlur stdDeviation="5" result="core"/>
      <feGaussianBlur in="SourceGraphic" stdDeviation="14" result="bloom"/>
      <feMerge><feMergeNode in="bloom"/><feMergeNode in="core"/><feMergeNode in="SourceGraphic"/></feMerge>
    </filter>
    <filter id="soft" x="-40%" y="-40%" width="180%" height="180%">
      <feGaussianBlur stdDeviation="5" result="b"/><feMerge><feMergeNode in="b"/><feMergeNode in="SourceGraphic"/></feMerge>
    </filter>
  </defs>
  <rect width="512" height="512" rx="96" fill="url(#bg)"/>
  <path d="${hex}" fill="none" stroke="${accent}" stroke-width="14" stroke-linejoin="round" filter="url(#glow)"/>
  <path d="${hex}" fill="${accent}" fill-opacity="0.08" transform="translate(256 230) scale(0.82) translate(-256 -230)"/>
  <text x="256" y="300" text-anchor="middle" font-size="170">${emoji}</text>
  <g font-family="Poppins, system-ui, sans-serif" font-weight="800" letter-spacing="-2">${wordmark(name, accent)}</g>
</svg>
`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  mkdirSync(OUT, { recursive: true });
  for (const [key, name, emoji, accent] of MEDALS) {
    writeFileSync(join(OUT, `badge_${key}-neon.svg`), medal(name, emoji, accent));
  }
  console.log(`wrote ${MEDALS.length} badge medals to public/icons/`);
}
